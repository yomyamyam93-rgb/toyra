/// 네발 동작 **단계표** — 이 파일이 사양서다. 숫자가 곧 동작이다.
///
/// ★한 동작을 통으로 만들지 않는다 (2026-08-05 사용자 "최소 6단계 많게는 20단계까지 나눠서").
///   "머리를 흔든다" 로 적으면 밋밋하거나 과해진다. 늑대 물기라면
///   *노림 → 웅크림 → 도약 → 체공 → 물기 → 흔들기 → 착지 → 물러남 → 정착* 아홉 단계고,
///   단계마다 뼈 열두 개가 각각 몇 도인지가 있어야 한다.
///
/// ★부호 (실측): **옆 + = 코 내림 · 꼬리 올림 · 다리 뒤로** / **위 + = 오른쪽** / **앞 + = 왼쪽으로 쓰러짐**
///
/// ★★정강이(무릎)만은 **어느 다리든 + = 접힘**으로 적는다. 앞다리는 접으면 발이 뒤로,
///   뒷다리는 접으면 발이 앞으로 오는데, 그 뒤집기는 `네발동작저작.다리` 가 대신 한다.
///   여기서는 "얼마나 접히나"만 생각하면 된다.
///
/// ★시간 배분은 3막 규칙을 따른다 — 예비 30~45% · **본동작 10~20%(가장 짧다)** · 여운 40~50%.
///   본동작을 길게 잡는 게 밋밋함의 첫째 원인이다. "빠르다"는 절대 속도가 아니라
///   예비와의 **대비**에서 나온다.
