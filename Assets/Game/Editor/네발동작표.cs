    //     · **굴곡 (t=.42)** 앞다리는 뒤로, 뒷다리는 앞으로 → 넷이 배 밑에 모인다
    //   늘었다 줄었다 하는 이 맥박이 곧 달리기다. 다리를 빨리 젓는 게 아니다.
