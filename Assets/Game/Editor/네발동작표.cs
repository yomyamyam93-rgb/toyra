        //   접는 건 발을 들어 옮길 때뿐이었다. 그래서 **통짜 막대기가 흔들리는 것**으로 보였다.
        //   사람 눈이 "구부러진다"고 읽는 건 **체중을 받아 굽는 순간**이지 허공에서 접는 게 아니다.
        //
        //   ★네 박자로 적는다 — 이 순서가 무릎 규칙이다:
        //     ①닿음(편 채) → ②흡수(굽음) → ③밀기(폄) → ④접기(크게 굽음)
