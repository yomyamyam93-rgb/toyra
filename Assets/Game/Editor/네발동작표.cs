        //   원인: 앞다리와 뒷다리에 **같은 허벅 각도표**를 물렸다. 그런데 두 다리는
        //   매달린 자리가 다르다 — 뒷다리는 골반, 앞다리는 **어깨**다. 어깨는 골반보다
        //   앞으로 기울어 붙어 있어서, 같은 각도를 주면 앞다리 궤적이 통째로 머리 쪽으로
        //   밀린다. 그래서 앞발만 허공을 젓는 것처럼 보였다.
        //   ☆뒷다리는 멀쩡했다는 사용자의 관찰이 정확히 이 구조를 가리킨다.
        //
        // ★+ 가 「다리 뒤로」다. 이 값만 키우면 앞발 구간이 더 뒤로 간다 — 눈으로 보고 맞춘다.
