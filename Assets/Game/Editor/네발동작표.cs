        //     자취에서 저절로 나온다 — 접지 중엔 뻗고, 흔들 땐 접힌다.
        // ★네발 걸음의 발 순서는 **옆순서**: 뒤왼 → 앞왼 → 뒤오 → 앞오, 25%씩.
        // ★★IK 는 아직 못 쓴다 (2026-08-06). 발자취를 넣어 봤더니 **시킨 자리에 발이
        //   안 놓였다** — 보폭이 명령값의 절반도 안 나오고, 한가운데가 쉬는 자리에서
        //   티라노는 +27cm 테러버드는 −37cm 로 **서로 반대로** 밀렸다 (둘 다 앞이 +z 인데도).
        //   각도를 밖에서 유도해 넣는 방식이 굽는 쪽의 합성과 안 맞는 것이라,
        //   부호를 뒤집는 걸로는 못 고친다. **수치 해로 다시 짤 때까지 각도표를 쓴다.**
