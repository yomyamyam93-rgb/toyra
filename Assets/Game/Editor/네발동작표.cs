    // ★네발 걸음의 발 순서는 **옆순서(lateral sequence)**: 뒤왼 → 앞왼 → 뒤오 → 앞오, 25%씩.
    //   대각 짝을 동시에 딛는 건 걷기가 아니라 속보(트로트)라 느긋한 걸음으로 안 읽힌다.
    // ★디딤 구간(0~0.6)만은 **선형**이 옳다 — 발은 땅에 붙어 있고 몸이 등속으로 지나가므로.
