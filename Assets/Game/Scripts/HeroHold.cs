    //   전엔 든 자세 하나뿐이라, 휘두를 때 팔은 그대로 두고 몽둥이만 세상 기준 yaw 로
    //   돌렸다. 그런데 든 자세에서는 몽둥이가 거의 **수직**이라, 수직 막대를 수직축으로
    //   돌려 봐야 실루엣이 안 바뀐다 — 눈에는 아무 일도 안 일어난 것이다.
    //   → 휘두름은 **팔이 위에서 앞아래로 내려오는 것**이어야 한다.
    [Header("내려친 자세 (휘두름의 끝)")]
    public Vector3 칠때어깨 = new Vector3(12f, 0f, 0f);
    // ★★오른쪽 위에서 들었으면 **왼쪽 아래로 가로질러** 후린다 (2026-08-05 사용자).
    //   손이 향할 방향 (-0.50, -0.58, 0.64) = 왼쪽·아래·앞 — 여기서 풀어낸 각도다.
    //
    // ★★각도를 되찾는 법 (직접 손대지 말 것):
    //   ①`FromToRotation` 으로 한 번에 고치려 들면 **발산한다.** 팔뚝이 몸 기준으로 따로
    //     고정돼 있어 회전 합성이 선형이 아니다 (59° → 78° → 127° 로 벌어졌다).
    //   ②그래서 **탐색**으로 푼다. 각도를 넣고 자세를 만들어 방향을 재는 걸 수천 번 하면 된다.
    //   ③★그때 **매번 애니메이터로 뼈를 되돌려야** 한다. 몸통은 `얹기`(더하기)라서
    //     안 되돌리면 비틀림이 누적돼 엉뚱한 값이 최적으로 잡힌다 — 실제로 한 번 속았다.
    public Vector3 칠때팔 = new Vector3(-131.4f, -122.7f, 72.1f);
    public Vector3 칠때팔뚝 = new Vector3(-12f, 0f, 0f);

    // ★★★팔만 움직이면 어색하다 (2026-08-04 사용자 "다른 곳들도 움직임이 있을텐데말야").
    //
    //   사람이 무언가를 내려칠 때 움직이는 건 팔이 아니라 **몸 전체**다. 골반이 먼저 돌고,
    //   그 힘이 허리를 타고 올라가 마지막에 손끝이 나간다 (운동 사슬). 팔만 돌리면
    //   「인형 팔을 집어 올린 것」처럼 보인다.
    //
    //   ★여기서는 팔처럼 **덮어쓰지 않고 얹는다** (`얹기`). 몸통은 걷는 동안 계속
    //     움직여야 하므로, 걷기 위에 비틀기만 더한다. 팔은 반대로 덮어써야 한다 —
    //     안 그러면 걸을 때 팔이 계속 앞뒤로 흔들려 무기가 떨린다 (위 주석 참고).
    [Header("몸통도 같이 (팔만 움직이면 어색하다)")]
    public bool 몸통참여 = true;
    [Tooltip("들 때 — 뒤로 젖히고(x−) 오른쪽으로 비튼다(y+)")]
    public Vector3 들때몸통 = new Vector3(-7f, 20f, 0f);
    [Tooltip("칠 때 — 앞으로 숙이고(x+) 왼쪽으로 돌아 나간다(y−)")]
    public Vector3 칠때몸통 = new Vector3(12f, -24f, 0f);
    [Tooltip("골반이 몸통의 몇 %를 따라가나 — 0.3 쯤이면 하체가 버티는 느낌이 산다")]
    [Range(0f, 1f)] public float 골반몫 = 0.3f;
    [Tooltip("머리 되돌리기 — 음수면 몸이 돌아도 시선이 앞에 남는다")]
    [Range(-1f, 1f)] public float 머리몫 = -0.35f;

    [Header("왼팔도 같이 (두 손으로 들 때)")]
    public bool 두손 = true;
    public Vector3 왼팔 = new Vector3(-95f, 0f, 25f);
    public Vector3 왼팔뚝 = new Vector3(-70f, 0f, 0f);

    [Header("느낌")]
    [Tooltip("드는 데 걸리는 빠르기 (클수록 빨리 든다)")] public float 따라붙기 = 8f;
    [Tooltip("어깨→팔→팔뚝이 늦게 따라오는 정도 (0 이면 셋이 동시에 꺾인다)")]
    [Range(0f, 0.5f)] public float 시차 = 0.18f;

    /// 0 = 평소 · 1 = 다 든 자세. 밖에서 넣는다
    [HideInInspector] public float 목표 = 0f;
    /// 0 = 든 자세 · 1 = 다 내려친 자세. 밖에서 넣는다
    [HideInInspector] public float 침 = 0f;

    /// 지금 얼마나 들었나 (0~1) — 밖에서 "다 감았나" 를 물어본다
    public float 지금 { get; private set; }
    Transform 어깨뼈, 팔뼈, 팔뚝뼈, 왼팔뼈, 왼팔뚝뼈, 몸뿌리;
    Transform 골반뼈, 허리뼈, 등뼈, 가슴뼈, 머리뼈;
    Quaternion 어깨기본, 팔기본, 팔뚝기본, 왼팔기본, 왼팔뚝기본;

    /// ★`Awake` 에서 잡는다 — 애니메이터가 아직 한 번도 안 돌아서 **뼈대 기본 자세**가 남아 있다.
    ///   `Start` 나 첫 `LateUpdate` 에서 잡으면 이미 걷는 도중 자세가 기준이 되어 어긋난다.
    void Awake() { 뼈잡기(); }

    /// ★★몸이 둘이 되면서(남/여) **켜져 있는 쪽에서만** 잡아야 한다 (2026-08-04).
    ///   꺼진 것까지 훑으면 나중에 걸린 쪽 뼈를 쥐게 되어, 팔이 **아무리 눌러도 안 올라간다**
    ///   (안 보이는 몸의 팔만 올라간다). 몸을 바꾸면 `HeroSwap` 이 이걸 다시 부른다.
    public void 뼈잡기()
    {
        어깨뼈 = 팔뼈 = 팔뚝뼈 = 왼팔뼈 = 왼팔뚝뼈 = null;
        // ★몸이 향한 쪽 — 각도를 이 축에서 돌린다 (`잡기` 주석 참고).
        //   뿌리(transform)가 아니라 **모델**이다. 모델은 180° 돌려 놓았을 수 있고,
        //   눈에 보이는 앞은 모델의 앞이다 (`HeroAnim.모델회전` 과 같은 이유).
        var an = GetComponentInChildren<Animator>();
        몸뿌리 = an != null ? an.transform : transform;
        foreach (var t in GetComponentsInChildren<Transform>(false))   // 켜진 것만
        {
            switch (t.name)
            {
                case "RightShoulder": 어깨뼈 = t; 어깨기본 = t.localRotation; break;
                case "RightArm":      팔뼈 = t; 팔기본 = t.localRotation; break;
                case "RightForeArm":  팔뚝뼈 = t; 팔뚝기본 = t.localRotation; break;
                case "LeftArm":       왼팔뼈 = t; 왼팔기본 = t.localRotation; break;
                case "LeftForeArm":   왼팔뚝뼈 = t; 왼팔뚝기본 = t.localRotation; break;
                // 몸통 — 덮어쓰지 않고 얹기만 하므로 기본 자세는 안 들고 있어도 된다
                // ★계층이 Hips → Spine02 → Spine01 → Spine → 어깨 순이다 (이름과 반대다)
                case "Hips":          골반뼈 = t; break;
                case "Spine02":       허리뼈 = t; break;
                case "Spine01":       등뼈 = t; break;
                case "Spine":         가슴뼈 = t; break;
                case "Head":          머리뼈 = t; break;
            }
        }
    }

    // ★★★★**집어드는 자세** (2026-08-12 사용자 "허리만 숙이게 한건아니지? 손목 팔 어깨 등
    //   허리 엉덩이 허벅지 종아리 발 목 머리 등등 다양한 리깅이 있는데 움직임을 넣어줘야").
    //   맞는 지적이었다 — 골반·허벅지·정강이·발목·척추는 `HeroAttack.웅크림` 이 이미
    //   움직이고 있었지만 **팔과 머리는 가만히 있었다.** 손을 안 뻗고 줍는 그림이었다.
    //   ☆여기 이미 어깨→팔→팔뚝 사슬과 몸통 사슬(골반→허리→등→가슴→머리)이 있으니
    //     새로 만들지 않고 **자세 한 벌만 더** 얹는다.
    //   ☆두 팔을 다 쓴다 — 한 손으로 새끼를 들어올리진 않는다.
    [Header("★집어들 때 (0~1 을 HeroCarry 가 민다)")]
    [Tooltip("어깨 — 앞아래로 낸다")] public Vector3 줍을때어깨 = new Vector3(38f, 0f, 0f);
    [Tooltip("위팔")] public Vector3 줍을때팔 = new Vector3(62f, 0f, -8f);
    [Tooltip("팔뚝 — 팔꿈치를 굽혀 감싸 안는다")] public Vector3 줍을때팔뚝 = new Vector3(-46f, 0f, 0f);
    [Tooltip("머리 — 보는 곳을 따라 숙인다")] public Vector3 줍을때머리 = new Vector3(26f, 0f, 0f);
    [HideInInspector] public float 줍기;          // 0 = 평소 · 1 = 완전히 뻗어 감쌈
    float 줍기지금;

    // ★★★★**머리 위로 들어올린다** (2026-08-13 사용자 "몸을 숙여 손을 뻗고, 들어서 머리위로
    //   올리고 들고 그상태로 또 걷기되고").
    //   ☆여태 자세가 **하나뿐**이었다 — 「숙여서 앞아래로 뻗기」. 그러니 다 든 뒤에도 팔이
    //     앞아래에 있어서, 짐승이 손에 달라붙어 끌려오는 그림이 됐다.
    //   ☆이제 두 자세다: `줍기`(숙여 뻗기) → `들올림`(머리 위로 받치기). 순서대로 섞인다.
    // ★★★**팔을 옆으로 벌리지 않는다 — 몸 앞쪽으로 모아 올린다** (2026-08-13 사용자 "그대로
    //   잡은채로 몸앞쪽으로 해서 팔을 들어올려야하는데, 양쪽으로 팔을 쭉 벌리면서 손을 올려,
    //   머리위에 들고있을때도 팔을 너무 많이 벌리고 들고있는거같아").
    //   ☆옛 값 `(-146, 0, 22)` 은 제가 지어낸 것이었다 — z 가 작아 팔이 옆으로 벌어졌다.
    //   ☆★위 `팔` 기본값 `(-16.4, -7.1, 162.4)` 이 이미 **"오른쪽 머리 위로 젖힌다"** 다.
    //     무기를 든 팔은 옆으로 안 벌어지고 몸 앞·위로 모인다 — **그 검증된 값을 기준으로 삼는다.**
    //     이 리그는 팔을 올릴 때 **z(롤)** 를 쓴다. 22 가 아니라 160 쪽이 맞다.
    [Header("★머리 위로 들어올릴 때 (HeroCarry 가 민다)")]
    [Tooltip("어깨 — 벌리지 않고 살짝만")] public Vector3 들올때어깨 = new Vector3(-14f, 0f, 0f);
    [Tooltip("위팔 — 몸 앞쪽으로 모아 머리 위로")] public Vector3 들올때팔 = new Vector3(-18f, -6f, 158f);
    [Tooltip("팔뚝 — 굽혀서 받친다")] public Vector3 들올때팔뚝 = new Vector3(-62f, 0f, 0f);
    [Tooltip("머리 — 앞을 본다 (음수가 듦)")] public Vector3 들올때머리 = new Vector3(-5f, 0f, 0f);
    [HideInInspector] public float 들올림;        // 0 = 숙여 뻗은 채 · 1 = 머리 위로 다 올림
    float 들올림지금;

    // ★★★★**줄을 양손으로 잡고 뒷걸음질로 끈다** (2026-08-12 사용자 "줄을 양손으로 잡고
    //   뒤로 걸으면서 끌고가도록").
    //   ☆여태 끌 때 사람은 **평소 걷는 자세 그대로**였다 — 두 손을 늘어뜨린 채 걷고
    //     줄만 따라왔다. 무게가 실린 느낌이 아니라 줄이 붙어 있는 그림이었다.
    //   ☆`줍기` 와 같은 방식이다 — 자세 한 벌을 더 얹고 `HeroCarry` 가 0~1 을 민다.
    //     새 사슬을 만들지 않으니 소유권이 안 겹친다 (어깨→팔→팔뚝, 골반→…→머리 그대로).
    // ★★★**두 손이 「줄 한 가닥」을 앞뒤로 쥔다** (2026-08-12 사용자 "팔이 꺾여있고 …
    //   두손으로 질질끄는 모션도 아니고").
    //   ☆옛 코드는 왼팔을 **오른팔의 좌우 대칭**으로 만들었다(`줍기` 방식 그대로). 그건
    //     새끼를 **감싸 안을** 때나 맞는 짓이다 — 줄은 한 가닥인데 두 손이 각자 다른 데를
    //     쥐고 있으니 팔이 꺾여 보였다.
    //   → **앞손(오른)은 멀리 뻗어 쥐고, 뒷손(왼)은 몸 가까이 당겨 쥔다.** 줄다리기 자세다.
    [Header("★줄을 끌 때 — 앞손 (0~1 을 HeroCarry 가 민다)")]
    [Tooltip("어깨 — 줄을 쥐러 앞으로 조금")] public Vector3 끌때어깨 = new Vector3(18f, 0f, 0f);
    [Tooltip("앞손 위팔 — 앞아래로 뻗어 쥔다")] public Vector3 끌때팔 = new Vector3(48f, 0f, -6f);
    [Tooltip("앞손 팔뚝 — 줄을 감아 쥐게 조금 굽힌다")] public Vector3 끌때팔뚝 = new Vector3(-32f, 0f, 0f);
    [Header("★줄을 끌 때 — 뒷손 (대칭이 아니다)")]
