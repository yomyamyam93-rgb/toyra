using System.Collections.Generic;
using UnityEngine;

/// 아이템의 **갈래** — 뭉치느냐 아니냐가 여기서 갈린다 (기획 5-7)
public enum 갈래 { 재료, 먹을것, 물건 }

/// 아이템 한 종류의 정의 — **표로 돈다. 코드에 종류를 박지 않는다.**
///
/// ★사용자 지적: *"돌이 몇갠지 나무가 몇갠지 UI로 표현해서 좆같았던 적이 있다.
///   아이템이 그것만 있는 게 아닌데."* → 옛 방식은 `고기·나무·돌` 셋이 **HUD 코드에 박혀**
///   있었다. 종류를 늘리려면 화면 코드를 고쳐야 했고, 화면은 글자로 도배됐다.
///   → 이제 **여기 한 줄만 추가하면** 창·무게·부패가 저절로 따라온다.
public class 아이템종
{
    public string 이름;
    public 갈래 갈래;
    /// 하나당 무게 (kg)
    public float 무게;
    /// 아이콘 대신 쓰는 색 (6장 — 장난감 톤: 단순한 면, 뚜렷한 경계)
    public Color 색;

    /// 상하는 데 걸리는 시간 (초). 0 이면 안 상한다. 하루 = 1200초
    public float 상하는데;
    /// 상하면 무엇이 되나 (비우면 그냥 사라지지 않고 「상함」 표시만)
    public string 상하면;

    /// 물건일 때 — 최대 내구. 0 이면 안 닳는다
    public float 내구;

    /// 이 도구가 여는 행위 (없으면 빈 칸) — `Harvest` 가 제일 좋은 것을 저절로 고른다
    public string 쓰임;
    /// 그 행위에서 얼마나 잘하나 (맨손 = 1)
    public float 성능 = 1f;
}

/// ★아이템 표 — **여기에 한 줄 추가하는 것이 「새 아이템을 만드는 일」의 전부다.**
public static class 아이템표
{
    static Dictionary<string, 아이템종> 표;
    public static readonly List<아이템종> 전부 = new List<아이템종>();

    static void 하나(string 이름, 갈래 g, float 무게, Color 색,
                     float 상하는데 = 0f, string 상하면 = null,
                     float 내구 = 0f, string 쓰임 = null, float 성능 = 1f)
    {
        var d = new 아이템종 {
            이름 = 이름, 갈래 = g, 무게 = 무게, 색 = 색,
            상하는데 = 상하는데, 상하면 = 상하면, 내구 = 내구, 쓰임 = 쓰임, 성능 = 성능
        };
        표[이름] = d; 전부.Add(d);
    }

    static 아이템표()
    {
        표 = new Dictionary<string, 아이템종>();

        // ── 재료 — 뭉친다. 하나하나가 다 똑같다
        하나("나무",   갈래.재료, 0.20f, new Color(0.42f, 0.28f, 0.16f));
        하나("돌",     갈래.재료, 0.50f, new Color(0.48f, 0.48f, 0.46f));
        하나("뼈",     갈래.재료, 0.15f, new Color(0.85f, 0.82f, 0.72f));
        하나("가죽",   갈래.재료, 0.40f, new Color(0.55f, 0.38f, 0.24f));
        하나("풀",     갈래.재료, 0.05f, new Color(0.45f, 0.62f, 0.30f));

        // ── 먹을 것 — ★덩이마다 신선도가 다르다. 그래서 안 뭉친다
        //    하루 = 1200초. 생고기는 하루 반, 구우면 나흘, 말리면 안 상한다
        하나("생고기",   갈래.먹을것, 0.30f, new Color(0.78f, 0.30f, 0.30f), 1800f, "상한고기");
        하나("구운고기", 갈래.먹을것, 0.28f, new Color(0.62f, 0.40f, 0.22f), 4800f, "상한고기");
        하나("말린고기", 갈래.먹을것, 0.15f, new Color(0.50f, 0.32f, 0.20f));
        하나("상한고기", 갈래.먹을것, 0.30f, new Color(0.42f, 0.45f, 0.30f));
        하나("열매",     갈래.먹을것, 0.08f, new Color(0.80f, 0.35f, 0.55f), 2400f, "상한고기");

        // ── 물건 — 하나씩. 닳은 정도가 다르다
        하나("몽둥이",   갈래.물건, 1.00f, new Color(0.58f, 0.44f, 0.28f), 내구: 120f, 쓰임: "때리기", 성능: 1f);
        하나("돌도끼",   갈래.물건, 1.20f, new Color(0.55f, 0.52f, 0.48f), 내구: 100f, 쓰임: "나무",   성능: 3f);
        하나("돌곡괭이", 갈래.물건, 1.50f, new Color(0.52f, 0.50f, 0.50f), 내구: 100f, 쓰임: "돌",     성능: 3f);
        하나("뼈칼",     갈래.물건, 0.40f, new Color(0.88f, 0.85f, 0.75f), 내구: 70f,  쓰임: "가죽",   성능: 3f);
        하나("창",       갈래.물건, 0.90f, new Color(0.60f, 0.48f, 0.30f), 내구: 80f,  쓰임: "찌르기", 성능: 1.5f);
        하나("밧줄",     갈래.물건, 0.30f, new Color(0.72f, 0.66f, 0.45f), 내구: 60f);
        하나("가죽물통", 갈래.물건, 0.50f, new Color(0.50f, 0.35f, 0.22f), 내구: 0f);
    }

    public static 아이템종 찾기(string 이름)
    {
        if (string.IsNullOrEmpty(이름)) return null;
        return 표.TryGetValue(이름, out var d) ? d : null;
    }
}

/// 실제로 가진 물건 한 덩이.
/// ★재료는 `개수` 로 뭉치고, 먹을 것·물건은 **하나씩** 따로 논다 (신선도·닳음이 제각각이라)
public class 아이템
{
    public 아이템종 종;
    /// 재료일 때만 쓴다 (먹을 것·물건은 언제나 1)
    public int 개수 = 1;
    /// 1 = 갓 만든 것 · 0 = 상함
    public float 신선 = 1f;
    /// 남은 내구 (물건만)
    public float 내구;

    public 아이템(아이템종 d, int n = 1)
    {
        종 = d; 개수 = d.갈래 == 갈래.재료 ? Mathf.Max(1, n) : 1;
        내구 = d.내구;
    }

    public float 무게 => 종.무게 * (종.갈래 == 갈래.재료 ? 개수 : 1);
    public bool 뭉치나 => 종.갈래 == 갈래.재료;
    public bool 상했나 => 종.상하는데 > 0f && 신선 <= 0f;

    /// 창에 띄울 곁들임 글 — **수치와 상태만** (11장: 설명문을 쓰지 않는다)
    public string 곁들임
    {
        get
        {
            if (뭉치나) return "×" + 개수;
            if (종.갈래 == 갈래.먹을것 && 종.상하는데 > 0f)
                return 신선 > 0.6f ? "신선" : (신선 > 0.25f ? "" : "곧 상함");
            if (종.갈래 == 갈래.물건 && 종.내구 > 0f)
                return Mathf.RoundToInt(내구 / 종.내구 * 100f) + "%";
            return "";
        }
    }
}
